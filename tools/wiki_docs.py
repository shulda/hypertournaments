#!/usr/bin/env python3
"""Render and check the research Wiki and the paper-to-Lean link catalogue.

The checked-in catalogue is the mathematical source of the correspondence.
Lean checks every named symbol through the generated CheckTheoremMap.lean;
this tool additionally verifies defining files, source anchors and Wiki links.
It never fetches a manuscript or requires a private repository at build time.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import sys
from urllib.parse import quote, unquote, urlsplit

from project_sources import lean_code, proof_placeholders

GENERATED = '<!-- Generated by tools/wiki_docs.py; edit docs/wiki-src/ and docs/catalogue/. -->\n\n'
STATUSES = {
    'proved': 'Proved',
    'definition': 'Definition / encoding',
    'background-instance': 'Background instance used here',
    'proof-variant': 'Alternative proof / scope note',
}
DECLARATION = re.compile(r'\b(?:theorem|lemma|def|abbrev|structure|class|inductive|opaque|instance)\s+([A-Za-z_][A-Za-z0-9_.\']*)')
MACRO = re.compile(r'\{\{([^{}]+)\}\}')
LINK = re.compile(r'(?<!!)\[[^\]\n]*\]\(([^)\n]+)\)')
MODULE = re.compile(r'[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*\Z')
NAME = re.compile(r'[A-Za-z_][A-Za-z0-9_\']*(?:\.[A-Za-z_][A-Za-z0-9_\']*)*\Z')


class WikiError(ValueError):
    """A source or generated-document invariant was violated."""


def read_json(path: Path):
    try:
        return json.loads(path.read_text(encoding='utf-8'))
    except (OSError, json.JSONDecodeError) as exc:
        raise WikiError(f'{path}: {exc}') from exc


def repository_path(root: Path, relative: str) -> Path:
    path = PurePosixPath(relative)
    if path.is_absolute() or '..' in path.parts or not path.parts:
        raise WikiError(f'Unsafe repository path: {relative}')
    result = root / path
    if not result.is_file():
        raise WikiError(f'Missing repository file: {relative}')
    return result


def module_path(module: str) -> str:
    if not MODULE.fullmatch(module):
        raise WikiError(f'Invalid Lean module: {module}')
    path = module.replace('.', '/') + '.lean'
    if module.startswith(('CCO.', 'PartiteConstruction.', 'SuccessorTree.')):
        return 'vendor/ramsey-transfer/' + path
    if module == 'Hypertournaments' or module.startswith('Hypertournaments.'):
        return path
    raise WikiError(f'Unsupported defining-module root: {module}')


def declaration_location(root: Path, name: str, module: str) -> dict:
    if not NAME.fullmatch(name):
        raise WikiError(f'Invalid Lean declaration name: {name}')
    path = module_path(module)
    code = lean_code(repository_path(root, path).read_text(encoding='utf-8'))
    # Namespace/section commands are sufficient for this catalogue: theorem
    # bodies need not be parsed. The generated Lean file independently checks
    # every complete name, while this scan checks its actual defining module.
    scope_command = re.compile(r'(?m)^[ \t]*(namespace|section|end)\b(?:[ \t]+([A-Za-z_][A-Za-z0-9_.]*))?')
    events = [(m.start(), 'scope', m) for m in scope_command.finditer(code)]
    events += [(m.start(), 'declaration', m) for m in DECLARATION.finditer(code)]
    scopes = []
    found = []
    for position, kind, match in sorted(events, key=lambda event: event[0]):
        if kind == 'scope':
            command, argument = match.groups()
            if command == 'end':
                if scopes:
                    scopes.pop()
            else:
                scopes.append((command, argument or ''))
            continue
        written = match.group(1)
        namespace = '.'.join(value for scope, value in scopes if scope == 'namespace')
        resolved = (written[len('_root_.'):] if written.startswith('_root_.')
                    else '.'.join(filter(None, [namespace, written])))
        if resolved == name:
            found.append(position)
    if len(found) != 1:
        reason = 'Ambiguous declaration' if found else 'Declaration not defined'
        raise WikiError(f'{reason}: {name} in {path}')
    return {'name': name, 'module': module, 'path': path,
            'line': code.count('\n', 0, found[0]) + 1}


def cell(text: str) -> str:
    return text.replace('|', r'\|').replace('\n', ' ')


def render_table(entries: list[dict]) -> str:
    blocks = []
    for entry in entries:
        source = ((entry['source_kind'] + ' ' + entry['number'])
                  if entry['number'] else entry['kind'].replace('-', ' ').title())
        references = '<br>'.join(f"[`{d['name']}`]({d['url']})" for d in entry['declarations'])
        modules = '<br>'.join(dict.fromkeys(
            f"[`{d['module']}`]({d['file_url']})" for d in entry['declarations']))
        rows = [f"| Source | {cell(source)}" +
                (f" · `{entry['label']}`" if entry['label'] else '') + ' |',
                f"| Scope | {cell(entry['scope'])} |",
                f"| Lean | {references} |", f"| Defining module | {modules} |",
                f"| Correspondence | {STATUSES[entry['status']]} |"]
        blocks.append(f'<a id="{entry["id"]}"></a>\n\n'
                      f'### {source}: {entry["title"]}\n\n'
                      '| Field | Reference |\n| --- | --- |\n' + '\n'.join(rows) +
                      ('\n\n' + entry['notes'] if entry['notes'] else ''))
    return '\n\n'.join(blocks)


def render_module_index(entries: list[dict]) -> str:
    """Reverse the checked correspondence, without claiming import usage."""
    files = {}
    for entry in entries:
        for declaration in entry['declarations']:
            path = declaration['path']
            row = files.setdefault(path, {'url': declaration['file_url'], 'entries': {}})
            # One source statement may list several declarations from this file.
            row['entries'][entry['id']] = entry
    rows = ['| Defining Lean file | Paper statements and definitions |', '| --- | --- |']
    for path, row in sorted(files.items()):
        links = []
        for _eid, entry in sorted(row['entries'].items()):
            reference = entry['source_kind'] + (' ' + entry['number'] if entry['number'] else '')
            title = f"{entry['document']}: {reference} — {entry['title']}"
            title = cell(title).replace('[', r'\[').replace(']', r'\]')
            links.append(f"[{title}]({entry['wiki_url']})")
        rows.append(f"| [`{path}`]({row['url']}) | " + '<br>'.join(links) + ' |')
    return '\n'.join(rows)


def validate_page_links(pages: dict[str, str]) -> None:
    for name, content in pages.items():
        for target in LINK.findall(content):
            target = target.strip().strip('<>')
            parsed = urlsplit(target)
            if parsed.scheme or parsed.netloc or target.startswith('#'):
                continue
            path = unquote(parsed.path)
            if not path:
                continue
            if path.endswith('.md'):
                path = path[:-3]
            # Relative links inside the Wiki must point to another maintained page.
            # Repository files use the {{file:...}} macro and therefore absolute URLs.
            if '/' in path or path not in pages:
                raise WikiError(f'{name}: unknown Wiki page link {target}')


def check_documentation_lean(root: Path, generated_checks: str) -> None:
    sources = [('docs/CheckTheoremMap.lean (generated)', generated_checks)]
    example = root / 'docs/Examples.lean'
    if example.is_file():
        sources.append(('docs/Examples.lean', example.read_text(encoding='utf-8')))
    for name, text in sources:
        findings = proof_placeholders(text)
        if findings:
            details = ', '.join(f'{token} on line {line}' for line, token in findings)
            raise WikiError(f'{name}: forbidden proof token: {details}')


def build_outputs(root: Path, repository: str | None = None,
                  source_ref: str | None = None) -> dict[Path, str]:
    catalogue = root / 'docs/catalogue'
    config = read_json(catalogue / 'papers.json')
    labels = read_json(catalogue / 'source-labels.json')
    if config.get('schema_version') != 1:
        raise WikiError('Unsupported catalogue schema_version')
    if config.get('source_revision') != labels.get('source_revision'):
        raise WikiError('Paper source revision and source-label revision disagree')
    repository = repository or config.get('repository', '')
    source_ref = source_ref or config.get('source_ref', '')
    if not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', repository):
        raise WikiError(f'Invalid GitHub repository: {repository}')
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_./-]*', source_ref) or '..' in source_ref:
        raise WikiError(f'Invalid source ref: {source_ref}')
    pdf_ref = config.get('pdf_ref', source_ref)
    if (not isinstance(pdf_ref, str)
            or not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_./-]*', pdf_ref)
            or '..' in pdf_ref):
        raise WikiError(f'Invalid PDF ref: {pdf_ref}')
    repo_url = 'https://github.com/' + repository
    wiki_url = repo_url + '/wiki'
    blob_url = repo_url + '/blob/' + quote(source_ref, safe='/')
    pdf_blob_url = repo_url + '/blob/' + quote(pdf_ref, safe='/')
    templates = {p.stem: p.read_text(encoding='utf-8') for p in sorted((root / 'docs/wiki-src').glob('*.md'))}
    if 'Home' not in templates:
        raise WikiError('The Wiki must have a Home.md source page')
    papers = config.get('papers', [])
    if not papers:
        raise WikiError('No papers in the catalogue')
    paper_ids = set()
    entry_ids = set()
    label_ids = set()
    symbols = {}
    all_entries = []
    document_entries = {}
    pdf_links = {}
    location_cache = {}
    for paper in papers:
        doc = paper.get('id')
        if not isinstance(doc, str) or not re.fullmatch(r'[a-z][a-z0-9-]*', doc) or doc in paper_ids:
            raise WikiError(f'Invalid or duplicate paper id: {doc}')
        paper_ids.add(doc)
        if paper.get('wiki_page') not in templates:
            raise WikiError(f'Missing Wiki page for paper {doc}: {paper.get("wiki_page")}')
        for field in ['title', 'author', 'filename', 'description']:
            if not isinstance(paper.get(field), str) or not paper[field].strip():
                raise WikiError(f'Paper {doc} lacks {field}')
        if 'pdf' in paper or 'pdf_sha256' in paper:
            pdf_path = paper.get('pdf')
            expected_hash = paper.get('pdf_sha256')
            if (not isinstance(pdf_path, str) or not pdf_path.strip()
                    or not isinstance(expected_hash, str)
                    or not re.fullmatch(r'[0-9a-f]{64}', expected_hash)):
                raise WikiError(f'Paper {doc} needs a PDF path and its lowercase pdf_sha256')
            pdf_file = repository_path(root, pdf_path)
            actual_hash = hashlib.sha256(pdf_file.read_bytes()).hexdigest()
            if actual_hash != expected_hash:
                raise WikiError(f'Paper {doc} PDF SHA-256 mismatch: {pdf_path}')
            pdf_links[doc] = f'[PDF]({pdf_blob_url}/{quote(pdf_path, safe="/")})'
        fragment = read_json(catalogue / f'{doc}.json')
        if fragment.get('document') != doc or not isinstance(fragment.get('entries'), list):
            raise WikiError(f'Incorrect document catalogue: {doc}')
        entries = []
        for item in fragment['entries']:
            entry = dict(item)
            eid = entry.get('id')
            if not isinstance(eid, str) or not re.fullmatch(r'[a-z][a-z0-9-]*', eid) or eid in entry_ids:
                raise WikiError(f'Invalid or duplicate entry id: {eid}')
            entry_ids.add(eid)
            for field in ['kind', 'title', 'scope']:
                if not isinstance(entry.get(field), str) or not entry[field].strip():
                    raise WikiError(f'Entry {eid} lacks {field}')
            status = entry.get('status')
            if status not in STATUSES:
                raise WikiError(f'Entry {eid} has invalid status: {status}')
            notes = entry.get('notes', '')
            if not isinstance(notes, str):
                raise WikiError(f'Entry {eid} has nontext notes')
            if status in {'proof-variant', 'background-instance'} and not notes.strip():
                raise WikiError(f'Entry {eid} must explain its {status} scope')
            entry['notes'] = notes
            label = entry.get('label')
            entry['label'] = label
            entry['number'] = None
            entry['source_kind'] = entry['kind'].replace('-', ' ').title()
            if label is not None:
                if not isinstance(label, str) or (doc, label) in label_ids:
                    raise WikiError(f'Duplicate or invalid source label: {doc}/{label}')
                label_ids.add((doc, label))
                metadata = labels.get('papers', {}).get(doc, {}).get(label)
                if not metadata:
                    raise WikiError(f'Unknown source label: {doc}/{label}')
                entry['number'] = metadata['number']
                entry['source_kind'] = metadata['kind']
            if not isinstance(entry.get('declarations'), list) or not entry['declarations']:
                raise WikiError(f'Entry {eid} has no Lean declarations')
            references = []
            seen = set()
            for declaration in entry['declarations']:
                name, module = declaration.get('name'), declaration.get('module')
                if not isinstance(name, str) or not isinstance(module, str):
                    raise WikiError(f'Entry {eid} has an invalid declaration reference')
                if name in seen:
                    raise WikiError(f'Entry {eid} repeats declaration {name}')
                seen.add(name)
                key = name, module
                if key not in location_cache:
                    location_cache[key] = declaration_location(root, name, module)
                ref = dict(location_cache[key])
                ref['file_url'] = blob_url + '/' + quote(ref['path'], safe='/')
                ref['url'] = ref['file_url'] + '#L' + str(ref['line'])
                references.append(ref)
                if name in symbols and symbols[name]['module'] != module:
                    raise WikiError(f'Declaration {name} assigned to two defining modules')
                symbols[name] = ref
            entry['declarations'] = references
            entry['document'] = doc
            entry['paper_title'] = paper['title']
            entry['wiki_page'] = paper['wiki_page']
            entry['wiki_url'] = wiki_url + '/' + quote(paper['wiki_page']) + '#' + eid
            entry['primary_url'] = references[0]['url']
            entries.append(entry)
            all_entries.append(entry)
        document_entries[doc] = entries

    def replace(match):
        macro = match.group(1)
        if macro == 'repo':
            return repo_url
        if macro == 'wiki':
            return wiki_url
        if macro == 'module-index':
            return render_module_index(all_entries)
        if macro.startswith('pdf:'):
            doc = macro[4:]
            if doc not in paper_ids:
                raise WikiError(f'Unknown PDF document: {doc}')
            if doc not in pdf_links:
                raise WikiError(f'No PDF recorded for paper: {doc}')
            return pdf_links[doc]
        if macro.startswith('table:'):
            doc = macro[6:]
            if doc not in document_entries:
                raise WikiError(f'Unknown document table: {doc}')
            return render_table(document_entries[doc])
        if macro.startswith('lean:'):
            name = macro[5:]
            if name not in symbols:
                raise WikiError(f'Unregistered Lean symbol macro: {name}')
            return f"[`{name}`]({symbols[name]['url']})"
        if macro.startswith('file:'):
            path = macro[5:]
            repository_path(root, path)
            return f'[`{path}`]({blob_url}/{quote(path, safe="/")})'
        raise WikiError(f'Unknown Wiki macro: {macro}')

    pages = {}
    for name, template in templates.items():
        # Repository-address macros make the source portable to the clean repository.
        if re.search(r'https://github\.com/[^/\s)]+/[^/\s)]+/(?:blob|tree)/', template):
            raise WikiError(f'{name}: use file/lean macros for repository source links')
        content = MACRO.sub(replace, template)
        if '{{' in content or '}}' in content:
            raise WikiError(f'{name}: unresolved Wiki macro')
        pages[name] = content.rstrip() + '\n'
    validate_page_links(pages)
    registry = {'schema_version': 1, 'repository': repository, 'source_ref': source_ref,
                'source_revision': config['source_revision'], 'papers': papers,
                'entries': all_entries}
    checks = ('-- Generated by tools/wiki_docs.py from docs/catalogue/.\n'
              '-- This checks names in Lean; defining-file and link checks are separate.\n'
              'import Hypertournaments\n\n' +
              ''.join('#check ' + name + '\n' for name in sorted(symbols)))
    check_documentation_lean(root, checks)
    outputs = {Path('docs/wiki') / (name + '.md'): GENERATED + content
               for name, content in pages.items()}
    outputs[Path('docs/theorem-map.json')] = json.dumps(registry, ensure_ascii=False, indent=2) + '\n'
    outputs[Path('docs/CheckTheoremMap.lean')] = checks
    return outputs


def write_or_check(root: Path, outputs: dict[Path, str], check: bool) -> None:
    expected_pages = {path for path in outputs if path.parent == Path('docs/wiki')}
    existing_pages = {path.relative_to(root) for path in (root / 'docs/wiki').glob('*.md')}
    stale = sorted(existing_pages - expected_pages)
    changed = sorted(path for path, content in outputs.items()
                     if not (root / path).is_file() or (root / path).read_text(encoding='utf-8') != content)
    if check and (changed or stale):
        names = ', '.join(map(str, changed + stale))
        raise WikiError('Generated documentation is stale: ' + names + '; run python3 tools/wiki_docs.py render')
    if check:
        return
    for path in stale:
        if not (root / path).read_text(encoding='utf-8').startswith(GENERATED):
            raise WikiError(f'Unmanaged generated-page destination: {path}')
        (root / path).unlink()
    for path, content in outputs.items():
        destination = root / path
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding='utf-8')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['render', 'check'])
    parser.add_argument('--repository', help='GitHub owner/repository for generated links')
    parser.add_argument('--ref', dest='source_ref', help='Source branch, release tag or commit for code links')
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1],
                        help=argparse.SUPPRESS)
    args = parser.parse_args()
    try:
        outputs = build_outputs(args.root, args.repository, args.source_ref)
        write_or_check(args.root, outputs, args.command == 'check')
    except (WikiError, TypeError, KeyError) as exc:
        print(str(exc), file=sys.stderr)
        raise SystemExit(1)
    registry = json.loads(outputs[Path('docs/theorem-map.json')])
    print(json.dumps({'command': args.command, 'pages': sum(p.parent == Path('docs/wiki') for p in outputs),
                      'statements': len(registry['entries']),
                      'declarations': len({d['name'] for e in registry['entries'] for d in e['declarations']}),
                      'repository': registry['repository'], 'source_ref': registry['source_ref']}))


if __name__ == '__main__':
    main()
